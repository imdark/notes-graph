#!/usr/bin/env node
/**
 * Regenerate the plugin-runtime ES module shims in
 * packages/frontend/core/public/plugin-runtime/.
 *
 *   node scripts/gen-plugin-runtime.mjs
 *
 * Run it after upgrading React. The shims re-export the host's React instance
 * to plugins; ES module named exports are static, so the export list has to be
 * written out rather than forwarded dynamically, and a stale list means a
 * plugin importing a newer hook fails to load.
 */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(
  repoRoot,
  'packages/frontend/core/public/plugin-runtime'
);

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const namedExports = mod =>
  Object.keys(mod)
    .filter(k => IDENT.test(k) && k !== 'default')
    .sort();

const preamble = (what, globalKey) => `/**
 * The host's ${what}, re-exported as an ES module.
 *
 * Plugins are loaded with a bare \`import()\` from a URL, so a plugin that
 * bundles its own React ends up with a SECOND copy: its hooks read a different
 * dispatcher than the host's renderer and throw the moment a component mounts.
 * The page's import map points the bare specifier at this file instead, so
 * host and plugin share one instance.
 *
 * The host publishes that instance on a global before any plugin can be
 * imported (modules/plugin/runtime.ts); this file only forwards it.
 *
 * GENERATED by scripts/gen-plugin-runtime.mjs - do not hand-edit.
 */
const runtime = globalThis.__NOTESGRAPH_PLUGIN_RUNTIME__;
if (!runtime || !runtime.${globalKey}) {
  throw new Error(
    '[plugin-runtime] the host has not published its ${what} yet - a plugin ' +
      'was imported before modules/plugin/runtime.ts ran'
  );
}
const mod = runtime.${globalKey};

export default mod;
`;

function emit(file, what, globalKey, mod) {
  const names = namedExports(mod);
  const body = names.map(n => `export const ${n} = mod.${n};`).join('\n');
  writeFileSync(join(outDir, file), preamble(what, globalKey) + body + '\n');
  console.log(`${file}: ${names.length} named exports`);
}

mkdirSync(outDir, { recursive: true });

const React = require('react');
emit('react.js', 'React instance', 'react', React);
emit(
  'jsx-runtime.js',
  'JSX runtime',
  'jsxRuntime',
  require('react/jsx-runtime')
);
emit(
  'jsx-dev-runtime.js',
  'development JSX runtime',
  'jsxDevRuntime',
  require('react/jsx-dev-runtime')
);

console.log(`react@${React.version} -> ${outDir}`);
